import type { SqlQueryOutput } from '@prisma/generator';
import ts from 'typescript';
import type { PrismaJsonTypesGeneratorConfig } from '../util/config';
import { createType, findTypeAnnotation } from '../util/create-signature';
import type { DeclarationWriter } from '../util/declaration-writer';

/** The prisma runtime type used for JSON columns inside a query `Result`. */
const RESULT_JSON_TYPES: ReadonlySet<string> = new Set(['JsonValue']);

/** The prisma runtime types used for JSON values accepted as query `Parameters`. */
const PARAMETER_JSON_TYPES: ReadonlySet<string> = new Set([
  'InputJsonObject',
  'InputJsonValue',
  'JsonValue'
]);

/**
 * What prisma writes for a column or parameter of each introspected scalar kind. An
 * annotation replaces exactly that node, so whatever prisma wrapped around it -- `| null`
 * for a nullable column, `[]` for an array one -- survives by construction.
 *
 * The `-array` kinds share their element kind's entry, because prisma spells them as the
 * same base with `[]` appended.
 */
const SCALAR_BASE_TYPES: Readonly<Record<string, string>> = {
  string: 'string',
  char: 'string',
  xml: 'string',
  uuid: 'string',
  int: 'number',
  float: 'number',
  double: 'number',
  bigint: 'bigint',
  bool: 'boolean',
  decimal: 'Decimal',
  datetime: 'Date',
  date: 'Date',
  time: 'Date',
  bytes: 'Bytes'
};

/**
 * The prisma scalar type a column of each introspected kind was read from.
 *
 * Prisma does not report which table a result column came from, but it does report the
 * column's kind, and that alone rules most models out: a `json` column cannot have come
 * from a `String` field, however many models happen to spell that column name. Looking a
 * column up under its scalar type keeps those models from colliding with each other.
 */
const FIELD_TYPES: Readonly<Record<string, string>> = {
  string: 'String',
  char: 'String',
  xml: 'String',
  uuid: 'String',
  int: 'Int',
  bigint: 'BigInt',
  float: 'Float',
  double: 'Float',
  bool: 'Boolean',
  decimal: 'Decimal',
  datetime: 'DateTime',
  date: 'DateTime',
  time: 'DateTime',
  bytes: 'Bytes',
  json: 'Json'
};

/**
 * The key a column's annotation is stored under: its name, qualified by the scalar type it
 * must have been read from. Kinds with no prisma scalar behind them -- enums, `null`,
 * `unknown` -- fall back to the bare name, which nothing registers, so they resolve to
 * nothing rather than to a same-named column of some unrelated type.
 */
export function columnDocsKey(kind: string, name: string) {
  const fieldType = FIELD_TYPES[kind.replace(/-array$/, '')];

  return fieldType ? `${fieldType}:${name}` : name;
}

/** A type an annotation resolved to, and the nodes it may replace. */
interface Replacement {
  readonly type: string;
  readonly targets: ReadonlySet<string>;
}

const isJsonKind = (kind: string) => kind === 'json' || kind === 'json-array';

/**
 * The nodes an annotation may replace within whatever prisma emitted for `kind`.
 *
 * `undefined` means the kind has no single node standing for the column's own type, so
 * there is nothing safe to swap and prisma's output is left alone. That covers `enum` --
 * spelled as an indexed access into `$DbEnums` -- along with `null`, `unknown`, and the
 * model-specific names prisma passes through for enum columns.
 */
function replaceableTypes(kind: string, jsonTypes: ReadonlySet<string>) {
  if (isJsonKind(kind)) {
    return jsonTypes;
  }

  const base = SCALAR_BASE_TYPES[kind.replace(/-array$/, '')];

  return base ? new Set([base]) : undefined;
}

/**
 * Parses `-- @pjt-type column_name annotation` comments from a SQL source string.
 *
 * These per-file annotations let users type JSON columns in complex queries (joins,
 * CTEs, column aliases) that don't map 1:1 to a Prisma model field. SQL-file
 * annotations take priority over model-based column docs for the query that contains
 * them.
 *
 * The `annotation` must follow the same syntax as Prisma schema doc-comments:
 * - `[TypeName]` – references `<namespace>.TypeName`
 * - `![InlineType]` – uses the inline type `(InlineType)` literally
 *
 * @example
 * ```sql
 * -- @pjt-type field_alias ![number]
 * SELECT id, field AS field_alias FROM "Model"
 * ```
 */
export function parseSqlAnnotations(sqlContent: string): Map<string, string> {
  const annotations = new Map<string, string>();

  for (const line of sqlContent.split('\n')) {
    const match = line.trim().match(/^--\s*@pjt-type\s+(\S+)\s+(.+?)\s*$/);

    if (match) {
      annotations.set(match[1]!, match[2]!);
    }
  }

  return annotations;
}

/**
 * Handles a TypedSQL query file by giving annotated columns and parameters their annotated
 * types, the same replacement the model payloads get.
 *
 * TypedSQL files are TypeScript modules generated by Prisma that represent typed SQL
 * queries. Each file exports a factory function and a namespace with `Parameters` and
 * `Result` types.
 *
 * Rather than rebuilding each type from the query metadata, only the node standing for the
 * column's own type *inside* what prisma emitted is swapped out — `JsonValue` for a JSON
 * column, `string` for a `String` one, and so on. That keeps everything prisma wrapped
 * around it — `| null` for nullable columns and `[]` for array ones — intact by
 * construction.
 */
export function handleTypedSqlFile(
  tsSource: ts.SourceFile,
  writer: DeclarationWriter,
  query: SqlQueryOutput,
  columnDocs: Map<string, string | undefined>,
  config: PrismaJsonTypesGeneratorConfig
) {
  const columnTypes = resolveResultColumnTypes(query, columnDocs, config);
  const parameterTypes = resolveParameterTypes(query, config);

  if (columnTypes.size === 0 && parameterTypes.size === 0) {
    return;
  }

  for (const child of tsSource.statements) {
    if (ts.isModuleDeclaration(child) && child.name.text === query.name) {
      handleQueryNamespace(child, tsSource, writer, columnTypes, parameterTypes);
      continue;
    }

    // The exported factory repeats the parameter types in its `as (...) => ...` cast
    if (parameterTypes.size > 0 && ts.isVariableStatement(child)) {
      handleFactoryDeclaration(child, tsSource, writer, query.name, parameterTypes);
    }
  }
}

/**
 * Maps each annotated result column name to the type it should be replaced with.
 *
 * JSON and non-JSON columns are opted in differently, because prisma's own output differs
 * in how useful it is. `JsonValue` says nothing, so a JSON column is replaced whether or
 * not an annotation was found (`unknown` when it was not, unless `allowAny` is set) --
 * which is what the model payloads do. `string` and friends are real types, so a column of
 * any other kind is replaced only when an annotation says what it should be. An
 * unannotated column -- or an ambiguous one, which reaches here as unannotated -- keeps
 * exactly what prisma wrote.
 */
function resolveResultColumnTypes(
  query: SqlQueryOutput,
  columnDocs: Map<string, string | undefined>,
  config: PrismaJsonTypesGeneratorConfig
) {
  const types = new Map<string, Replacement>();

  for (const column of query.resultColumns) {
    const targets = replaceableTypes(column.typ, RESULT_JSON_TYPES);

    if (!targets) {
      continue;
    }

    const documentation = columnDocs.get(column.name);

    if (!documentation && (config.allowAny || !isJsonKind(column.typ))) {
      continue;
    }

    types.set(column.name, { type: createType(documentation, config), targets });
  }

  return types;
}

/**
 * Maps the index of each annotated parameter to the type it should be replaced with.
 *
 * Parameters are opt-in whatever their kind: they are only replaced when explicitly
 * annotated in the `-- @param` description. There is no model field to read an annotation
 * from -- a parameter is matched by position, not by name -- and an unannotated JSON
 * parameter keeps prisma's `InputJsonObject`, which is a far more useful input type than
 * `unknown`.
 */
function resolveParameterTypes(query: SqlQueryOutput, config: PrismaJsonTypesGeneratorConfig) {
  const types = new Map<number, Replacement>();

  query.parameters.forEach((parameter, index) => {
    const targets = replaceableTypes(parameter.typ, PARAMETER_JSON_TYPES);

    if (!targets) {
      return;
    }

    const documentation = parameter.documentation ?? undefined;

    // Descriptions are free text, so only replace when one holds a real annotation
    if (!findTypeAnnotation(documentation)) {
      return;
    }

    types.set(index, { type: createType(documentation, config), targets });
  });

  return types;
}

/** Rewrites the `Result` and `Parameters` type aliases inside the query namespace. */
function handleQueryNamespace(
  namespace: ts.ModuleDeclaration,
  tsSource: ts.SourceFile,
  writer: DeclarationWriter,
  columnTypes: Map<string, Replacement>,
  parameterTypes: Map<number, Replacement>
) {
  const body = namespace.body;

  if (!body || !ts.isModuleBlock(body)) {
    return;
  }

  for (const statement of body.statements) {
    if (!ts.isTypeAliasDeclaration(statement)) {
      continue;
    }

    if (statement.name.text === 'Result' && ts.isTypeLiteralNode(statement.type)) {
      handleResultType(statement.type, tsSource, writer, columnTypes);
      continue;
    }

    if (statement.name.text === 'Parameters' && ts.isTupleTypeNode(statement.type)) {
      handleParameterTuple(statement.type, tsSource, writer, parameterTypes);
    }
  }
}

/** Replaces the JSON type of every annotated column in a `Result` type literal. */
function handleResultType(
  typeLiteral: ts.TypeLiteralNode,
  tsSource: ts.SourceFile,
  writer: DeclarationWriter,
  columnTypes: Map<string, Replacement>
) {
  for (const member of typeLiteral.members) {
    if (!ts.isPropertySignature(member) || !member.type || !member.name) {
      continue;
    }

    const replacement = columnTypes.get(getMemberName(member.name));

    if (replacement) {
      replaceBaseTypes(member.type, tsSource, writer, replacement);
    }
  }
}

/** Replaces the JSON type of every annotated parameter in a `Parameters` tuple. */
function handleParameterTuple(
  tuple: ts.TupleTypeNode,
  tsSource: ts.SourceFile,
  writer: DeclarationWriter,
  parameterTypes: Map<number, Replacement>
) {
  tuple.elements.forEach((element, index) => {
    const replacement = parameterTypes.get(index);

    if (!replacement) {
      return;
    }

    // Prisma names its tuple members (`[filter: InputJsonObject]`)
    const type = ts.isNamedTupleMember(element) ? element.type : element;

    replaceBaseTypes(type, tsSource, writer, replacement);
  });
}

/**
 * Replaces the JSON parameter types in the `as (...) => $runtime.TypedSql<...>` cast of
 * the exported query factory, which restates them outside of the namespace.
 */
function handleFactoryDeclaration(
  statement: ts.VariableStatement,
  tsSource: ts.SourceFile,
  writer: DeclarationWriter,
  queryName: string,
  parameterTypes: Map<number, Replacement>
) {
  for (const declaration of statement.declarationList.declarations) {
    if (!ts.isIdentifier(declaration.name) || declaration.name.text !== queryName) {
      continue;
    }

    const initializer = declaration.initializer;

    if (!initializer || !ts.isAsExpression(initializer)) {
      continue;
    }

    if (!ts.isFunctionTypeNode(initializer.type)) {
      continue;
    }

    initializer.type.parameters.forEach((parameter, index) => {
      const replacement = parameterTypes.get(index);

      if (replacement && parameter.type) {
        replaceBaseTypes(parameter.type, tsSource, writer, replacement);
      }
    });
  }
}

/**
 * Stacks a replacement for every occurrence of one of `replacement.targets` found within
 * `node`, leaving the surrounding type syntax (`| null`, `[]`, ...) untouched.
 */
function replaceBaseTypes(
  node: ts.TypeNode,
  tsSource: ts.SourceFile,
  writer: DeclarationWriter,
  replacement: Replacement
) {
  for (const target of findBaseTypeNodes(node, replacement.targets)) {
    // Uses getStart() (not pos) to exclude leading trivia so the
    // space between the colon and the type is preserved.
    writer.replace(target.getStart(tsSource), target.end, replacement.type);
  }
}

/** Collects every node within `node` whose written type is one of `targets`. */
function findBaseTypeNodes(node: ts.Node, targets: ReadonlySet<string>) {
  const found: ts.Node[] = [];

  const visit = (current: ts.Node) => {
    const name = baseTypeName(current);

    if (name !== undefined && targets.has(name)) {
      found.push(current);
      return;
    }

    current.forEachChild(visit);
  };

  visit(node);

  return found;
}

/**
 * The name of the type `node` writes, for the two spellings prisma uses to name a column's
 * own type: a reference such as `Date` or `$runtime.JsonValue`, and the primitive keywords.
 * Anything else -- a union, an array, a `null` literal, an indexed access into `$DbEnums`
 * -- has no name to match, and is descended into rather than replaced.
 */
function baseTypeName(node: ts.Node) {
  if (ts.isTypeReferenceNode(node)) {
    // Matches `JsonValue` as well as qualified `$runtime.JsonValue`
    return ts.isQualifiedName(node.typeName) ? node.typeName.right.text : node.typeName.text;
  }

  switch (node.kind) {
    case ts.SyntaxKind.StringKeyword:
      return 'string';
    case ts.SyntaxKind.NumberKeyword:
      return 'number';
    case ts.SyntaxKind.BooleanKeyword:
      return 'boolean';
    case ts.SyntaxKind.BigIntKeyword:
      return 'bigint';
    default:
      return undefined;
  }
}

/** Reads a member name, unwrapping the quotes of `'quoted-column'` style names. */
function getMemberName(name: ts.PropertyName) {
  return ts.isStringLiteral(name) || ts.isIdentifier(name) ? name.text : name.getText();
}
